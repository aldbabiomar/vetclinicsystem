-- VetClinicSystem — migration 0001: the baseline schema (PostgreSQL).
--
-- The whole schema of the first release. Every later change is a new
-- numbered file beside this one; see schema.py for the rules. Until 1.0.0 is
-- published this file may be edited in place (no install has applied it).
--
-- Money: every amount is NUMERIC(15,3) — 12 digits before the point holds
-- the largest IQD amount, 3 after holds the fils — under BOTH money settings
-- (money.py). An IQ clinic's amounts are whole dinars stored as .000; a JO
-- clinic's use all three places. Quantities that are multiplied against a
-- price are NUMERIC(10,3), and percentages NUMERIC(5,2), so no arithmetic
-- ever mixes float and Decimal. Physical measurements (weight_kg), counts
-- never multiplied by a price (stock_counted, received_since_prior,
-- reorder_threshold, target_coverage_days, change_qty) are NUMERIC(10,3) too.
--
-- Time: business dates are DATE. Every event time is TIMESTAMPTZ, written
-- from clock.now() — the clinic's zone (clock.py) — and read back aware. A
-- request puts its session in that zone, so `::date` here and clock.today()
-- in Python name the same day.

