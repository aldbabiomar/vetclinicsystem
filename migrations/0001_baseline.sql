-- Inventory Catalog: Medical / Retail
CREATE TABLE inventory_list (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Medical' CHECK (category IN ('Medical','Retail')),
    unit TEXT,
    track_expiry BOOLEAN NOT NULL DEFAULT TRUE,
    cost_price NUMERIC(15,3),
    distributor_id INTEGER,
    -- 'Owned' (you bought this stock outright — the default) or
    -- 'Consignment' (a distributor's stock, sitting on your shelf; you
    -- owe them cost_price per unit only once it sells). Only meaningful
    -- for category='Retail' — enforced in app.py, not here. For a
    -- Consignment item, cost_price keeps its existing meaning (per-unit
    -- cost) but the *payee* changes: it's what's owed to distributor_id,
    -- not what the clinic itself paid — same column, same downstream
    -- COGS math, different real-world counterparty.
    ownership_type TEXT NOT NULL DEFAULT 'Owned' CHECK (ownership_type IN ('Owned','Consignment')),
    -- Set the moment this item most recently flipped Owned -> Consignment
    -- (app.py's consignment_items_bulk_edit). NULL if it's never been
    -- Consignment. consignment_balance() floors its sales/refund scan at
    -- this date per item, on top of the distributor-level period_start,
    -- so a sale from before the item was actually Consignment (e.g. years
    -- of prior Retail sales) never gets swept into what's owed.
    consignment_since TIMESTAMPTZ,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    barcode TEXT UNIQUE,
    -- Which of the two mutually-exclusive ways this item's barcode was set
    -- up: a real code entered/scanned in from the manufacturer's own
    -- packaging, or one this app generated internally. NULL alongside a
    -- NULL barcode when neither has ever been set up. Never both at once —
    -- enforced in app.py, not just here.
    barcode_source TEXT CHECK (barcode_source IN ('manual','generated')),
    notes TEXT,
    -- A Consignment item is by definition somebody's stock — the whole
    -- consignment layer (balance, overview, the receiving/shrinkage/
    -- returns pickers) inner-joins distributors, so an item in this state
    -- with no distributor silently disappears from all of it while still
    -- selling as consignment stock. See ORPHANED_RECORDS_AUDIT.md F-07.
    CONSTRAINT inventory_consignment_needs_distributor_ck
        CHECK (ownership_type <> 'Consignment' OR distributor_id IS NOT NULL),
    FOREIGN KEY (distributor_id) REFERENCES distributors(id),
    -- Amounts: never NaN (Postgres sorts NaN above every number, so a
    -- plain `>= 0` passes it), and never below what the routes allow.
    CHECK (cost_price IS NULL OR (cost_price >= 0 AND cost_price <> 'NaN'))
);

-- Price List: Service / Medicine / Retail
-- Medicine billing lines are priced by range and do NOT touch inventory stock.
-- Only Retail rows (optionally linked to an inventory item) are sold via POS and move stock.
CREATE TABLE price_list (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Service' CHECK (category IN ('Service','Medicine','Retail')),
    cost_price NUMERIC(15,3),
    sale_price NUMERIC(15,3),
    notes TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    linked_item_id INTEGER,             -- Retail rows only: links to inventory_list.id for POS
    can_discount BOOLEAN NOT NULL DEFAULT FALSE,   -- if false, a bill containing this item can't have a discount applied
    FOREIGN KEY (linked_item_id) REFERENCES inventory_list(id),
    -- Amounts: never NaN (Postgres sorts NaN above every number, so a
    -- plain `>= 0` passes it), and never below what the routes allow.
    CHECK (cost_price IS NULL OR (cost_price >= 0 AND cost_price <> 'NaN')),
    CHECK (sale_price IS NULL OR (sale_price >= 0 AND sale_price <> 'NaN'))
);

-- ============================================================ AUDITS (whole-catalog Save/Confirm sessions)
-- One session = one shelf-walk. "Not Started Yet" is simply the absence of a session
-- for a date; a session becomes 'Confirmed' (locked, can't be edited) the moment the
-- user presses Confirm, otherwise it stays 'Draft' ("Saved") and can be resumed/edited.
-- Only Confirmed sessions count toward Inventory Status / Ordering Sheet history.
CREATE TABLE audit_sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_date DATE NOT NULL,
    performed_by INTEGER,
    status TEXT NOT NULL DEFAULT 'Draft' CHECK (status IN ('Draft','Confirmed')),
    created_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ,
    FOREIGN KEY (performed_by) REFERENCES users(id)
);

CREATE TABLE audit_session_lines (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id INTEGER NOT NULL,
    item_id INTEGER NOT NULL,
    stock_counted NUMERIC(10,3),
    received_since_prior NUMERIC(10,3) NOT NULL DEFAULT 0,
    reorder_threshold NUMERIC(10,3),             -- NULL = inherit from the last confirmed audit
    critical_item INTEGER,           -- NULL = inherit
    target_coverage_days NUMERIC(10,3),          -- NULL = inherit
    nearest_expiry_date DATE,
    notes TEXT,
    FOREIGN KEY (session_id) REFERENCES audit_sessions(id),
    FOREIGN KEY (item_id) REFERENCES inventory_list(id),
    -- Counts are physical quantities: never negative, never NaN. NaN is the
    -- one that matters -- it is not just bad data, it disables the guards
    -- that read it (SIMULATION_AUDIT_2026-09-11.md F2/F5). A plain `>= 0`
    -- would NOT catch it: Postgres sorts NaN above every number, so
    -- 'NaN' >= 0 is true. Infinity cannot be stored in NUMERIC(10,3) at all.
    CHECK (stock_counted IS NULL OR (stock_counted >= 0 AND stock_counted <> 'NaN')),
    CHECK (received_since_prior >= 0 AND received_since_prior <> 'NaN'),
    CHECK (reorder_threshold IS NULL OR (reorder_threshold >= 0 AND reorder_threshold <> 'NaN')),
    CHECK (target_coverage_days IS NULL OR (target_coverage_days >= 0 AND target_coverage_days <> 'NaN')),
    -- One line per item per session — lets _save_audit_lines() use a
    -- single INSERT ... ON CONFLICT DO UPDATE instead of a
    -- check-then-insert, closing the race where two concurrent saves for
    -- the same item could both insert.
    UNIQUE (session_id, item_id)
);
CREATE INDEX idx_auditlines_session ON audit_session_lines(session_id);
CREATE INDEX idx_auditlines_item ON audit_session_lines(item_id);

-- Real-time stock movement — ONLY from POS Retail sales (not Medicine billing).
CREATE TABLE inventory_transactions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id INTEGER NOT NULL,
    change_qty NUMERIC(10,3) NOT NULL CHECK (change_qty <> 'NaN'),
    reason TEXT NOT NULL,            -- 'sale' / 'manual_adjustment'
    ref_id TEXT,
    timestamp TIMESTAMPTZ NOT NULL,
    user_id INTEGER,
    FOREIGN KEY (item_id) REFERENCES inventory_list(id),
    -- See ORPHANED_RECORDS_AUDIT.md F-19 — 14 user-referencing columns
    -- across this schema had no FK; nothing dangles today (no delete-user
    -- route exists, deactivate only), but the protection was accidental.
    -- RESTRICT matches how both apps already behave.
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT
);
-- (item_id, timestamp): current stock is the last audit's count plus every
-- movement for that item after the audit's timestamp.
CREATE INDEX idx_invtxn_item_ts ON inventory_transactions(item_id, timestamp);

