-- ============================================================ REFUNDS (Admin only)
-- Two kinds: 'retail' (one or more products returned, identified by barcode,
-- with an option to put the stock back) and 'service' (a straight revenue
-- reduction against a Visit or Inpatient case, no stock impact). Both reduce
-- revenue in the P&L for the month the refund itself was processed in —
-- not the original sale/visit's month — matching normal accounting practice.
CREATE TABLE refunds (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_type TEXT NOT NULL CHECK (refund_type IN ('retail','service')),
    refund_date DATE NOT NULL,
    amount NUMERIC(15,3) NOT NULL,
    restocked BOOLEAN NOT NULL DEFAULT FALSE,   -- retail only: were the returned items put back into inventory?
    -- Retail only — which POS sale this refund is against. Required at
    -- the app layer (refund_retail_save() in app.py) so a retail refund
    -- can never be recorded against an item that was never actually
    -- sold, or for more than was sold minus what's already been
    -- refunded — see refund_items.sale_item_id for the per-line
    -- quantity/price tie-back.
    sale_id INTEGER,
    -- Service refunds anchor on exactly one of these three, mirroring
    -- payments.visit_id / inpatient_case_id / boarding_id. boarding_id was
    -- missing until 2026-09-10: money could be taken for a boarding stay
    -- (payments.boarding_id) and there was no way to give it back, because
    -- refunds_anchor_ck below required a visit or an inpatient case.
    visit_id INTEGER,                          -- service only
    inpatient_case_id INTEGER,              -- service only
    boarding_id INTEGER,                    -- service only
    reason TEXT,
    -- How the money was actually handed back — 'Cash', 'Card', or
    -- 'Transfer' (same vocabulary as sales.payment_method). Not
    -- necessarily the same method the original sale/payment used; Cash
    -- Register needs this to know which bucket to subtract a refund from.
    refund_method TEXT CHECK (refund_method IN ('Cash','Card','Transfer')),
    processed_by INTEGER,
    created_at TIMESTAMPTZ NOT NULL,
    -- Snapshot of the originating sale's/bill's cleanup_amount at the
    -- moment this refund was recorded — see CLEANUP_FEATURE_PLAN.md §4.5.
    -- Written once, not a live lookup, so this row stays self-contained
    -- even if the original bill's cleanup_amount changes afterward.
    cleanup_amount_at_refund NUMERIC(15,3) NOT NULL DEFAULT 0,
    -- A refund always reverses exactly one thing: a POS sale (retail), or
    -- one visit, one inpatient case, or one boarding stay (service). A
    -- goodwill/no-specific-record refund is handled through Cash Register
    -- instead, not this table. See ORPHANED_RECORDS_AUDIT.md F-05.
    CONSTRAINT refunds_anchor_ck CHECK (
        (refund_type = 'retail'  AND sale_id IS NOT NULL
            AND visit_id IS NULL AND inpatient_case_id IS NULL AND boarding_id IS NULL)
     OR (refund_type = 'service' AND sale_id IS NULL
            AND (visit_id IS NOT NULL)::int
              + (inpatient_case_id IS NOT NULL)::int
              + (boarding_id IS NOT NULL)::int = 1)
    ),
    FOREIGN KEY (sale_id) REFERENCES sales(id),
    FOREIGN KEY (visit_id) REFERENCES visits(id),
    FOREIGN KEY (inpatient_case_id) REFERENCES inpatient_cases(id),
    FOREIGN KEY (boarding_id) REFERENCES boarding_sessions(id),
    -- See F-19.
    FOREIGN KEY (processed_by) REFERENCES users(id) ON DELETE RESTRICT,
    -- Amounts: never NaN (Postgres sorts NaN above every number, so a
    -- plain `>= 0` passes it), and never below what the routes allow.
    CHECK (amount >= 0 AND amount <> 'NaN'),
    CHECK (cleanup_amount_at_refund >= 0 AND cleanup_amount_at_refund <> 'NaN')
);
CREATE INDEX idx_refunds_date ON refunds(refund_date);
CREATE INDEX idx_refunds_sale ON refunds(sale_id);
CREATE INDEX idx_refunds_visit ON refunds(visit_id);
CREATE INDEX idx_refunds_case ON refunds(inpatient_case_id);
CREATE INDEX idx_refunds_boarding ON refunds(boarding_id);

CREATE TABLE refund_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id INTEGER NOT NULL,
    item_id INTEGER NOT NULL,
    quantity NUMERIC(10,3) NOT NULL,
    unit_price NUMERIC(15,3) NOT NULL,
    line_total NUMERIC(15,3) NOT NULL,
    -- The specific sale_items row this line is refunding against — lets
    -- refund_retail_save() price from what was actually charged (not
