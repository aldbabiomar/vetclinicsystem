-- Manual bookkeeping for what a distributor has billed you and what
-- you've paid them — a lump-sum charge per bill, payments recorded
-- against it, balance always computed (never stored). Not linked to
-- inventory, POS, or any report; every bill is a manual entry, same as
-- the paper/memory tracking this replaces.
CREATE TABLE distributor_bills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distributor_id INTEGER NOT NULL,
    bill_date DATE NOT NULL,
    bill_reference TEXT,                 -- the distributor's own paper/invoice number, optional
    total_amount NUMERIC(15,3) NOT NULL CHECK (total_amount >= 0),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    created_by INTEGER,
    FOREIGN KEY (distributor_id) REFERENCES distributors(id),
    FOREIGN KEY (created_by) REFERENCES users(id),
    -- Amounts: never NaN (Postgres sorts NaN above every number, so a
    -- plain `>= 0` passes it), and never below what the routes allow.
    CHECK (total_amount <> 'NaN')
);
CREATE INDEX idx_distbills_distributor ON distributor_bills(distributor_id);

CREATE TABLE distributor_bill_payments (
