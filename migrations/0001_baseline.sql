-- ============================================================ OWNERS / PATIENTS
CREATE TABLE owners (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT,
    address TEXT,
    notes TEXT,
    -- Rewards card (features/REWARDS_CARD_PLAN.md). is_member and
    -- member_expires_on are deliberately separate facts: expiry never flips
    -- is_member, so "lapsed" stays distinguishable from "never joined".
    -- A card is active when is_member AND (member_expires_on IS NULL OR
    -- member_expires_on >= today) -- computed at read time through one
    -- helper, never by a background job that could stop running silently.
    is_member BOOLEAN NOT NULL DEFAULT FALSE,
    member_card_number TEXT,
    member_since DATE,
    -- NULL means the card never expires; the enroll form always pre-fills
    -- today + settings.member_term_months, so NULL only arises if someone
    -- clears the field on purpose.
    member_expires_on DATE,
    member_enrolled_by INTEGER REFERENCES users(id) ON DELETE RESTRICT
);
-- Nothing in the app looked up an existing owner by phone before
-- inserting a new one, so re-entering an existing owner's info (e.g. from
-- the "new patient" visit form) or double-submitting the new-owner form
-- silently created a duplicate row instead of failing or linking to the
-- existing owner. A plain UNIQUE index on a nullable column allows any
-- number of owners with no phone on file (each NULL is distinct in
-- Postgres) while rejecting a second owner with the same phone outright —
-- app.py's owner_new()/visit_new_patient() catch the resulting
-- IntegrityError and redirect to the existing owner instead of erroring.
CREATE UNIQUE INDEX idx_owners_phone_unique ON owners(phone) WHERE phone IS NOT NULL;
-- One card number, one owner. Partial, so any number of owners may hold
-- no card at all.
CREATE UNIQUE INDEX idx_owners_member_card ON owners(member_card_number)
    WHERE member_card_number IS NOT NULL;

CREATE TABLE patients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INTEGER NOT NULL,
    animal_name TEXT,
    species TEXT,
    sex TEXT,
    age_note TEXT,
    repro_status TEXT,
    housing TEXT,
    notes TEXT,
    microchip TEXT,          -- optional; unique when present (index below)
    FOREIGN KEY (owner_id) REFERENCES owners(id)
);
CREATE INDEX idx_patients_owner ON patients(owner_id);
-- A plain unique index would make the column effectively single-valued
-- (every NULL distinct in Postgres, but every blank string equal), so it is
-- partial: any number of patients may have no chip on file, while a second
-- patient carrying a chip already recorded is rejected outright. app.py
-- checks first and catches the IntegrityError for the concurrent case.
CREATE UNIQUE INDEX idx_patients_microchip_unique ON patients(microchip)
    WHERE microchip IS NOT NULL;

