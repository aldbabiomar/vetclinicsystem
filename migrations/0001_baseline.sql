-- ============================================================ CASH REGISTER
-- Unifies every place money actually changes hands on a given day (POS
-- sales, Visit/Inpatient/Boarding payments, and refunds netted as
-- negative) for end-of-day cash-up against what's physically in the till.
CREATE TABLE cash_register_payouts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payout_date DATE NOT NULL,
    amount NUMERIC(15,3) NOT NULL,
    reason TEXT NOT NULL,
    logged_by INTEGER,
    created_at TIMESTAMPTZ NOT NULL,
    FOREIGN KEY (logged_by) REFERENCES users(id),
    -- Amounts: never NaN (Postgres sorts NaN above every number, so a
    -- plain `>= 0` passes it), and never below what the routes allow.
    CHECK (amount > 0 AND amount <> 'NaN')
);
CREATE INDEX idx_cashpayouts_date ON cash_register_payouts(payout_date);

-- One immutable historical entry per audit — a re-audit of the same day
-- adds a new row rather than overwriting the old one.
CREATE TABLE cash_register_audits (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_date DATE NOT NULL,
    system_cash NUMERIC(15,3) NOT NULL,
    system_card NUMERIC(15,3) NOT NULL,
    system_transfer NUMERIC(15,3) NOT NULL,
    counted_cash NUMERIC(15,3) NOT NULL,
    difference NUMERIC(15,3) NOT NULL,      -- counted_cash - system_cash
    status TEXT NOT NULL CHECK (status IN ('Deficit','Surplus','Perfect')),
    notes TEXT,
    performed_by INTEGER,
    created_at TIMESTAMPTZ NOT NULL,
    FOREIGN KEY (performed_by) REFERENCES users(id),
    -- Amounts: never NaN (Postgres sorts NaN above every number, so a
    -- plain `>= 0` passes it), and never below what the routes allow.
    CHECK (counted_cash >= 0 AND counted_cash <> 'NaN'),
    CHECK (system_cash <> 'NaN'),
    CHECK (system_card <> 'NaN'),
    CHECK (system_transfer <> 'NaN'),
    CHECK (difference <> 'NaN')
);
CREATE INDEX idx_cashaudits_date ON cash_register_audits(audit_date);

-- ============================================================ OPEX / P&L (monthly is the source; yearly rolls it up)
CREATE TABLE monthly_opex (
    month TEXT PRIMARY KEY,           -- 'YYYY-MM'
    rent NUMERIC(15,3) NOT NULL DEFAULT 0,
    salaries NUMERIC(15,3) NOT NULL DEFAULT 0,
    utilities NUMERIC(15,3) NOT NULL DEFAULT 0,
    marketing NUMERIC(15,3) NOT NULL DEFAULT 0,
    other NUMERIC(15,3) NOT NULL DEFAULT 0,
    -- Amounts: never NaN (Postgres sorts NaN above every number, so a
    -- plain `>= 0` passes it), and never below what the routes allow.
    CHECK (rent >= 0 AND rent <> 'NaN'),
    CHECK (salaries >= 0 AND salaries <> 'NaN'),
    CHECK (utilities >= 0 AND utilities <> 'NaN'),
    CHECK (marketing >= 0 AND marketing <> 'NaN'),
    CHECK (other >= 0 AND other <> 'NaN')
);


-- ============================================================ APPOINTMENTS
-- Slot grid is generated dynamically from settings (appt_start_time / appt_end_time /
-- appt_slot_minutes) — no fixed slot table needed; slot labels (each slot's own start
-- time, e.g. '09:00', '09:30'...) are derived at render time from that range.
CREATE TABLE appointments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appt_date DATE NOT NULL,
    slot_label TEXT NOT NULL,          -- the slot's start time, e.g. '09:00', '09:30'...
    resource_type TEXT NOT NULL CHECK (resource_type IN ('vet','grooming')),
    resource_id INTEGER,                  -- users.id when resource_type='vet'; NULL for grooming
    pet_name TEXT NOT NULL,
    owner_name TEXT NOT NULL,
    appointment_type TEXT NOT NULL CHECK (appointment_type IN ('Medical','Grooming')),
    reason TEXT,
    created_by INTEGER,
    created_at TIMESTAMPTZ NOT NULL,
    -- resource_id is the one that already demonstrably orphans —
    -- logic.orphaned_appointments() exists precisely because this
    -- reference can stop resolving. See F-19.
    FOREIGN KEY (resource_id) REFERENCES users(id) ON DELETE RESTRICT,
    FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE RESTRICT
);
CREATE INDEX idx_appt_date ON appointments(appt_date);

-- Enforces at the database level what logic.slot_conflict() only checks at
-- the application level: two appointments can't occupy the same slot for
-- the same vet/groomer. The app-level check-then-insert alone has a race
-- window — two concurrent bookings for the same slot can both pass the
-- check before either inserts. COALESCE(resource_id, 0) is needed because
-- resource_id is NULL for grooming rows, and Postgres otherwise treats
-- every NULL as distinct (so two grooming rows for the same slot would
-- never actually collide on a plain (appt_date, slot_label, resource_type,
-- resource_id) unique index).
CREATE UNIQUE INDEX uq_appointments_slot
    ON appointments (appt_date, slot_label, resource_type, COALESCE(resource_id, 0));


-- Layer 1 of operational monitoring: one row per self-check run.
-- reported_at is set by heartbeat.py once that result has been sent; NULL
-- means it has not been (or the heartbeat is disabled, which is the
-- default). Pruned to 180 rows by selfcheck.record().
CREATE TABLE self_check_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ran_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('ok','warn','fail')),
    findings TEXT,
    reported_at TIMESTAMPTZ
);
CREATE INDEX idx_selfcheck_ran ON self_check_log(ran_at DESC);
