-- Billing: Automatic (priced line items) OR Manual (single lump amount)
CREATE TABLE billing (
    visit_id INTEGER PRIMARY KEY,
    billing_type TEXT NOT NULL DEFAULT 'Automatic' CHECK (billing_type IN ('Automatic','Manual')),
    -- codes column removed — Automatic billing is driven entirely by
    -- visit_billing_lines (price_id + quantity rows), not a comma string.
    manual_amount NUMERIC(15,3),               -- Manual: single lump sum, exported as one "Veterinary Services" line
    date_billed DATE,
    discount_percent NUMERIC(5,2) NOT NULL DEFAULT 0,
    discount_applied_by INTEGER,
    -- Which kind of discount discount_percent holds. A member's rewards
    -- card and a staff discount share this one slot on purpose: every
    -- money reader already reads discount_percent, and a second column
    -- would be one more thing each of them could forget. A bill never
    -- carries both (the card is the only discount a member's bill can
    -- take), so one slot is enough. See features/REWARDS_CARD_PLAN.md A1.
    discount_source TEXT NOT NULL DEFAULT 'staff' CHECK (discount_source IN ('staff','member')),
    notes TEXT,
    -- The final payable figure for this bill (what compute_bill_totals()
    -- actually charges), kept in sync by logic.refresh_visit_billing_total()
    -- every time lines/discount/manual_amount change. Reports read this
    -- instead of re-deriving subtotal*(1-discount%) independently.
    total NUMERIC(15,3) NOT NULL DEFAULT 0,
    -- "Clean Up" — a capped, explicit staff write-off applied at payment
    -- time (see CLEANUP_FEATURE_PLAN.md). Cumulative running total ever
    -- forgiven on this bill.
    cleanup_amount NUMERIC(15,3) NOT NULL DEFAULT 0,
    cleanup_applied_by INTEGER,
