def local_phone():
    """A mobile number as staff type it in the run's setting — the trunk 0,
    then the setting's local digits (9 in JO, 10 in IQ) — unique per call, so
    a test never meets a number already on file."""
    import uuid
    digits = _money.current().phone_local_length
    return "07" + str(uuid.uuid4().int)[:digits - 1].ljust(digits - 1, "0")


def amount(jo_value):
    """An amount written the way JO writes it, in the setting the test runs
    under: unchanged under JO, a thousand times larger under IQ ("12.000" is
    12,000 IQD).

    For a test about billing, refunds or reports rather than about one
    setting's arithmetic, so that it runs under both. Write values that are
    multiples of 0.250, results included: under IQ they are then whole
    250-dinar amounts, and nothing rounds."""
    from decimal import Decimal
    value = Decimal(str(jo_value))
    if _money.current().code == "IQ":
        value *= 1000
    return value.quantize(Decimal("0.001"))


def _store_money_setting(code):
    """Write the setting to the test database, skipping the round-trip when
    the previous test already left it at this value."""
    global _stored_money_code
    if not TEST_DB_URL or _stored_money_code == code:
        return
    import psycopg
    with psycopg.connect(TEST_DB_URL) as con:
        con.execute(
            "INSERT INTO settings (key, value) VALUES ('money_setting', %s) "
            "ON CONFLICT (key) DO UPDATE SET value = excluded.value", (code,))
        con.commit()
    _stored_money_code = code


def forget_stored_money_setting():
    """Call after a test changes the setting itself (e.g. through Settings),
    so the next test re-writes its own instead of trusting the cache."""
    global _stored_money_code
    _stored_money_code = None


@pytest.fixture(autouse=True)
def money_setting(request):
    marker = request.node.get_closest_marker("money")
    code = (marker.args[0] if marker else run_money_code()).upper()
    setting = _money.SETTINGS[code]
    _store_money_setting(code)
    token = _money.set_current(setting)
    # The clinic's clock follows the money setting's zone here (no test sets
    # the Time Zone setting unless it says so), exactly as a request would
    # resolve it. The `db` fixture connects after this, in the same zone.
    from vcs import clock as _clock
    clock_token = _clock.set_current(setting.timezone)
    try:
        yield setting
    finally:
        _clock.reset_current(clock_token)
        _money.reset_current(token)
