@pytest.fixture
def db(flask_app):
    """A direct connection for arranging fixtures and asserting on stored
    rows — deliberately separate from the request-scoped pool the app uses,
    so a test reads what was actually committed rather than what a shared
    transaction is holding."""
    from vcs.db import pool as dbmod
    con = dbmod.connect()
    try:
        yield con
    finally:
        # A failed statement leaves Postgres refusing everything else on this
        # connection ("current transaction is aborted"). Rolling back before
        # close keeps one broken test from being reported as a broken fixture.
        try:
            con.rollback()
        except Exception:
            pass
        con.close()


# ---------------------------------------------------------------------------
# The money setting
# ---------------------------------------------------------------------------
# VetClinicSystem runs under a money setting, IQ or JO (money.py). Every test
# runs under one. A test (or its module, via `pytestmark`) marked
# `@pytest.mark.money("IQ")` or `("JO")` always runs under that setting: it
# asserts that setting's values. Every other test runs under the RUN's
# setting — the isolated environment's (TEST_DATABASE_URL on 55491 is iq,
# 55492 is jo), or VCS_TEST_MONEY=IQ|JO, or JO when neither says. That is
# what makes the two runs CLAUDE.md §5 asks for two different runs: until
# 2026-09-27 every unmarked test ran under JO in both, and the "iq" run
# repeated the "jo" run except for the tests marked IQ.
#
# The setting is made active in-process (money.set_current) for tests that
# call logic/money directly, AND written to the test database's settings
# table, because routes — through the test client or the live app the
# browser tests drive — read it from there on every request.
from vcs import money as _money
_stored_money_code = None
_ENV_PORTS = {"55491": "IQ", "55492": "JO"}


def run_money_code():
    """The money setting an unmarked test runs under in this run."""
    explicit = os.environ.get("VCS_TEST_MONEY", "").strip().upper()
    if explicit:
        if explicit not in _money.SETTINGS:
            raise pytest.UsageError(f"VCS_TEST_MONEY={explicit!r}: expected IQ or JO")
        return explicit
    port = (TEST_DB_URL or "").rsplit("@", 1)[-1].split("/", 1)[0].rsplit(":", 1)[-1]
    return _ENV_PORTS.get(port, "JO")


def pytest_configure(config):
    config.addinivalue_line(
        "markers", 'money(code): run this test under money setting "IQ" or "JO" '
                   "(unmarked: the run's setting, see run_money_code)")


@pytest.fixture(scope="session")
def vendor():
    """An ephemeral vendor signing key, trusted for this test process only
    (plan §14.4), and the vendor tool's own functions to mint tokens with it.
    Nothing here is written to disk, and the production launchers never
    trust a key at run time."""
    import types
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    sys.path.insert(0, str(REPO_ROOT / "scripts" / "vendor"))
    import vcs_vendor
    from vcs import config
    from vcs.licensing import tokens
    key = Ed25519PrivateKey.generate()
    public = vcs_vendor.public_bytes(key)
    tokens.trust_for_tests(vcs_vendor.kid_for(public), public)
    install_id = config.INSTALL_ID

    def license(install=None, **fields):
        from datetime import datetime, timedelta, timezone
        payload = vcs_vendor.license_payload(key, install or install_id, "Test Clinic",
                                             datetime.now(timezone.utc) + timedelta(days=365))
        payload.update(fields)
        return vcs_vendor.sign(key, payload)

    def dev_pass(install=None, hours=8, **fields):
        payload = vcs_vendor.pass_payload(key, install or install_id, "Test Developer", hours=hours)
        payload.update(fields)
        return vcs_vendor.sign(key, payload)

    return types.SimpleNamespace(key=key, tool=vcs_vendor, install_id=install_id,
                                 license=license, dev_pass=dev_pass)


